#!/usr/bin/env bash
# Builds database/UPGRADE_TENANT.sql: every idempotent migration in one file,
# to paste into the Supabase SQL Editor of each EXISTING tenant.
#
#   bash scripts/build-upgrade-sql.sh
#
# Re-run this whenever a numbered migration is added or changed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/database/migrations"
OUT="$ROOT/database/UPGRADE_TENANT.sql"

# Order matters. CLEAN_RESET is NOT included (destructive, new tenants only).
FILES=(
  002_collection_snapshots.sql
  003_coupon_usage_rpc.sql
  004_soft_delete_trash.sql
  006_addon_system.sql
  007_channel_manager.sql
  008_security_hardening.sql
)

{
  cat <<'HEADER'
-- =============================================================
-- UPGRADE_TENANT.sql — bring an EXISTING tenant up to date
--
-- GENERATED by scripts/build-upgrade-sql.sh from migrations 002–008.
-- Do not edit by hand: edit the numbered migration and re-run the script.
--
-- How to use: open the tenant's Supabase project → SQL Editor → paste this
-- whole file → Run. Repeat for every tenant (each has its own Supabase).
--
-- Safe:
--   - Every statement is idempotent (running it twice does no harm).
--   - Wrapped in a transaction: if anything fails, NOTHING is applied.
--   - Does not delete or overwrite content (entries, collections, media).
-- Requires the core schema (the tenant was created with CLEAN_RESET.sql).
-- The last query prints a checklist: every column should be `true`.
-- =============================================================

BEGIN;

HEADER

  for f in "${FILES[@]}"; do
    echo ""
    echo "-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>"
    echo "-- >>> $f"
    echo "-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>"
    echo ""
    cat "$DIR/$f"
    echo ""
  done

  cat <<'FOOTER'

COMMIT;

-- Checklist (all columns should be true)
SELECT
    to_regclass('public.collection_snapshots') IS NOT NULL                          AS snapshots,
    to_regprocedure('public.bump_coupon_usage(uuid,integer,integer)') IS NOT NULL     AS coupon_limits,
    EXISTS (SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'entries'
              AND column_name = 'deleted_at')                                         AS trash,
    to_regclass('public.addon_configs') IS NOT NULL                                   AS addons,
    to_regclass('public.channel_connections') IS NOT NULL                             AS channel_manager,
    to_regprocedure('public.generate_new_api_key_for_user(uuid,text)') IS NOT NULL    AS api_key_button,
    EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'profiles_prevent_role_change')   AS role_protection,
    to_regclass('public.addon_cookie_notice_consents') IS NOT NULL                    AS cookie_consents,
    EXISTS (SELECT 1 FROM storage.buckets WHERE id = 'media')                         AS media_bucket;
FOOTER
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
