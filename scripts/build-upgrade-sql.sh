#!/usr/bin/env bash
# Builds database/UPGRADE_TENANT.sql: every idempotent migration in one file,
# to paste into the Supabase SQL Editor of each EXISTING tenant.
#
#   bash scripts/build-upgrade-sql.sh
#
# Re-run this whenever a numbered migration is added or changed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/database/migrations"
OUT="$ROOT/database/UPGRADE_TENANT.sql"

# Order matters. CLEAN_RESET is NOT included (destructive, new tenants only).
FILES=(
  002_collection_snapshots.sql
  003_coupon_usage_rpc.sql
  004_soft_delete_trash.sql
  006_addon_system.sql
  007_channel_manager.sql
  008_security_hardening.sql
  009_schema_status.sql
  010_addons_improvements.sql
)

{
  cat <<'HEADER'
-- =============================================================
-- UPGRADE_TENANT.sql — bring an EXISTING tenant up to date
--
-- GENERATED by scripts/build-upgrade-sql.sh from migrations 002–010.
-- Do not edit by hand: edit the numbered migration and re-run the script.
--
-- How to use: open the tenant's Supabase project → SQL Editor → paste this
-- whole file → Run. Repeat for every tenant (each has its own Supabase).
--
-- Safe:
--   - Every statement is idempotent (running it twice does no harm).
--   - Wrapped in a transaction: if anything fails, NOTHING is applied.
--   - Does not delete or overwrite content (entries, collections, media).
-- Requires the core schema (the tenant was created with CLEAN_RESET.sql).
-- The last query prints a checklist: every value should be `true`.
-- =============================================================

BEGIN;

HEADER

  for f in "${FILES[@]}"; do
    echo ""
    echo "-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>"
    echo "-- >>> $f"
    echo "-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>"
    echo ""
    cat "$DIR/$f"
    echo ""
  done

  cat <<'FOOTER'

COMMIT;

-- Checklist: every value should be true (schema_version = latest)
SELECT key AS feature, value AS ok
FROM jsonb_each(kiban_schema_status())
ORDER BY key;
FOOTER
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
